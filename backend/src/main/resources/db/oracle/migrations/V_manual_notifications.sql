-- Apply once as SPL3_APP to an existing Oracle schema before starting the updated backend.
-- Existing application rows remain unchanged. Do not rerun schema.sql.
CREATE TABLE app_notifications (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19,0) NOT NULL,
    github_project_id NUMBER(19,0) NOT NULL,
    pull_request_id NUMBER(19,0) NOT NULL,
    notification_type VARCHAR2(255 CHAR) NOT NULL,
    title VARCHAR2(255 CHAR) NOT NULL,
    message VARCHAR2(255 CHAR) NOT NULL,
    read_flag NUMBER(1,0) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    read_at TIMESTAMP(6),
    dedup_key VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_notification_project FOREIGN KEY (github_project_id) REFERENCES github_projects(id),
    CONSTRAINT fk_notification_pr FOREIGN KEY (pull_request_id) REFERENCES pull_requests(id),
    CONSTRAINT uk_notification_dedup UNIQUE (dedup_key),
    CONSTRAINT ck_notification_read CHECK (read_flag IN (0, 1))
);
CREATE INDEX ix_notifications_user_created ON app_notifications(user_id, created_at);
CREATE INDEX ix_notifications_user_unread ON app_notifications(user_id, read_flag);

