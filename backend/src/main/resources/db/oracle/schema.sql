-- Fresh, empty application schema for Oracle Database 19c or newer.
-- Apply once as the dedicated application user before starting with the oracle profile.
-- Hibernate validates this schema at startup; it does not create or update Oracle tables.

CREATE TABLE users (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_id VARCHAR2(255 CHAR),
    username VARCHAR2(255 CHAR),
    email VARCHAR2(255 CHAR),
    avatar_url VARCHAR2(255 CHAR),
    role VARCHAR2(255 CHAR),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6)
);

CREATE TABLE github_projects (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19,0) NOT NULL,
    github_repo_id NUMBER(19,0) NOT NULL,
    name VARCHAR2(255 CHAR) NOT NULL,
    full_name VARCHAR2(255 CHAR) NOT NULL,
    html_url VARCHAR2(255 CHAR) NOT NULL,
    owner_login VARCHAR2(255 CHAR) NOT NULL,
    owner_avatar_url VARCHAR2(255 CHAR),
    language VARCHAR2(255 CHAR),
    description VARCHAR2(1000 CHAR),
    created_at TIMESTAMP(6),
    CONSTRAINT fk_projects_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE pull_requests (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id NUMBER(19,0) NOT NULL,
    github_pr_id NUMBER(19,0) NOT NULL,
    pr_number NUMBER(10,0) NOT NULL,
    title VARCHAR2(255 CHAR) NOT NULL,
    state VARCHAR2(255 CHAR) NOT NULL,
    html_url VARCHAR2(255 CHAR),
    body CLOB,
    head_sha VARCHAR2(255 CHAR),
    base_sha VARCHAR2(255 CHAR),
    synced_files_head_sha VARCHAR2(255 CHAR),
    synced_files_base_sha VARCHAR2(255 CHAR),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6),
    CONSTRAINT fk_pr_project FOREIGN KEY (project_id) REFERENCES github_projects(id)
);

CREATE TABLE pull_request_files (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id NUMBER(19,0) NOT NULL,
    sha VARCHAR2(255 CHAR),
    filename VARCHAR2(255 CHAR),
    status VARCHAR2(255 CHAR),
    additions NUMBER(10,0),
    deletions NUMBER(10,0),
    changes NUMBER(10,0),
    patch CLOB,
    CONSTRAINT fk_files_pr FOREIGN KEY (pull_request_id) REFERENCES pull_requests(id)
);

CREATE TABLE pull_request_comments (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id NUMBER(19,0) NOT NULL,
    github_comment_id NUMBER(19,0),
    path VARCHAR2(255 CHAR),
    position NUMBER(10,0),
    body CLOB,
    user_login VARCHAR2(255 CHAR),
    created_at TIMESTAMP(6),
    CONSTRAINT fk_comments_pr FOREIGN KEY (pull_request_id) REFERENCES pull_requests(id)
);

CREATE TABLE analysis_runs (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id NUMBER(19,0) NOT NULL,
    status VARCHAR2(255 CHAR) NOT NULL,
    started_at TIMESTAMP(6),
    completed_at TIMESTAMP(6),
    analyzed_candidate_count NUMBER(10,0),
    analyzed_head_sha VARCHAR2(255 CHAR),
    analyzed_base_sha VARCHAR2(255 CHAR),
    publication_status VARCHAR2(255 CHAR) DEFAULT 'NOT_PUBLISHED' NOT NULL,
    github_review_id NUMBER(19,0),
    github_review_url VARCHAR2(255 CHAR),
    review_published_at TIMESTAMP(6),
    published_head_sha VARCHAR2(255 CHAR),
    publication_failure VARCHAR2(255 CHAR),
    CONSTRAINT ck_run_status CHECK (status IN ('PENDING','RUNNING','COMPLETED','FAILED')),
    CONSTRAINT fk_run_pr FOREIGN KEY (pull_request_id) REFERENCES pull_requests(id)
);

CREATE TABLE satd_findings (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_run_id NUMBER(19,0) NOT NULL,
    filename VARCHAR2(255 CHAR) NOT NULL,
    line_number NUMBER(10,0),
    comment_text CLOB,
    preceding_code CLOB,
    succeeding_code CLOB,
    satd_probability FLOAT(53) NOT NULL,
    non_satd_probability FLOAT(53) NOT NULL,
    confidence FLOAT(53) NOT NULL,
    debt_category VARCHAR2(255 CHAR),
    category_reason CLOB,
    category_rule_version VARCHAR2(255 CHAR),
    severity_score NUMBER(10,0),
    severity_reason CLOB,
    severity_rule_version VARCHAR2(255 CHAR),
    method_length NUMBER(10,0),
    method_complexity NUMBER(10,0),
    method_metrics_rule_version VARCHAR2(255 CHAR),
    risk_evidence CLOB,
    risk_evidence_rule_version VARCHAR2(255 CHAR),
    security_flag NUMBER(1,0),
    ai_suggestion CLOB,
    ai_suggestion_generated_at TIMESTAMP(6),
    ai_suggestion_provider_model VARCHAR2(255 CHAR),
    ai_suggestion_prompt_version VARCHAR2(255 CHAR),
    detected_at TIMESTAMP(6),
    CONSTRAINT ck_finding_security CHECK (security_flag IN (0,1)),
    CONSTRAINT fk_finding_run FOREIGN KEY (analysis_run_id) REFERENCES analysis_runs(id)
);

-- Ownership and sync lookups; do not add uniqueness absent from current entity mappings.
CREATE INDEX ix_users_github_id ON users(github_id);
CREATE INDEX ix_projects_user_repo ON github_projects(user_id, github_repo_id);
CREATE INDEX ix_prs_project ON pull_requests(project_id);
CREATE INDEX ix_prs_github_id ON pull_requests(github_pr_id);
CREATE INDEX ix_files_pr ON pull_request_files(pull_request_id);
CREATE INDEX ix_comments_pr ON pull_request_comments(pull_request_id);
CREATE INDEX ix_runs_pr_status_done ON analysis_runs(pull_request_id, status, completed_at);
CREATE INDEX ix_findings_run ON satd_findings(analysis_run_id);

-- Fresh installs only. Existing installations use migrations/V_manual_notifications.sql.
CREATE TABLE app_notifications (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19,0) NOT NULL,
    github_project_id NUMBER(19,0) NOT NULL,
    pull_request_id NUMBER(19,0) NOT NULL,
    notification_type VARCHAR2(255 CHAR) NOT NULL,
    title VARCHAR2(255 CHAR) NOT NULL,
    message VARCHAR2(255 CHAR) NOT NULL,
    read_flag NUMBER(1,0) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    read_at TIMESTAMP(6),
    dedup_key VARCHAR2(255 CHAR) NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_notification_project FOREIGN KEY (github_project_id) REFERENCES github_projects(id),
    CONSTRAINT fk_notification_pr FOREIGN KEY (pull_request_id) REFERENCES pull_requests(id),
    CONSTRAINT uk_notification_dedup UNIQUE (dedup_key),
    CONSTRAINT ck_notification_read CHECK (read_flag IN (0, 1))
);
CREATE INDEX ix_notifications_user_created ON app_notifications(user_id, created_at);
CREATE INDEX ix_notifications_user_unread ON app_notifications(user_id, read_flag);

-- Fresh installs only. Existing Oracle installations use migrations/V_manual_design_patterns.sql.
CREATE TABLE repository_pattern_profiles (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id NUMBER(19,0) NOT NULL,
    analyzed_commit_sha VARCHAR2(40 CHAR),
    default_branch VARCHAR2(100 CHAR),
    analyzed_at TIMESTAMP(6),
    java_file_count NUMBER(10,0),
    status VARCHAR2(255 CHAR) NOT NULL,
    progress VARCHAR2(255 CHAR) NOT NULL,
    failure_message VARCHAR2(255 CHAR),
    CONSTRAINT fk_pattern_profile_project FOREIGN KEY (project_id) REFERENCES github_projects(id),
    CONSTRAINT ck_pattern_profile_status CHECK (status IN ('RUNNING','COMPLETED','FAILED'))
);
CREATE INDEX ix_pattern_profiles_project ON repository_pattern_profiles(project_id, id);

CREATE TABLE pattern_occurrences (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id NUMBER(19,0) NOT NULL,
    pattern_type VARCHAR2(255 CHAR) NOT NULL,
    pattern_family VARCHAR2(255 CHAR) NOT NULL,
    confidence VARCHAR2(255 CHAR) NOT NULL,
    rationale CLOB,
    confidence_reason CLOB,
    evidence_json CLOB,
    CONSTRAINT fk_pattern_occurrence_profile FOREIGN KEY (profile_id) REFERENCES repository_pattern_profiles(id),
    CONSTRAINT ck_pattern_family CHECK (pattern_family IN ('GOF','ARCHITECTURAL')),
    CONSTRAINT ck_pattern_confidence CHECK (confidence IN ('HIGH','MEDIUM','LOW'))
);
CREATE INDEX ix_pattern_occurrences_profile ON pattern_occurrences(profile_id);

CREATE TABLE pr_pattern_checks (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pull_request_id NUMBER(19,0) NOT NULL,
    profile_id NUMBER(19,0) NOT NULL,
    checked_head_sha VARCHAR2(40 CHAR),
    checked_base_sha VARCHAR2(40 CHAR),
    checked_at TIMESTAMP(6) NOT NULL,
    status VARCHAR2(255 CHAR) NOT NULL,
    progress VARCHAR2(255 CHAR) NOT NULL,
    failure_message VARCHAR2(255 CHAR),
    findings_json CLOB,
    CONSTRAINT fk_pattern_check_pr FOREIGN KEY (pull_request_id) REFERENCES pull_requests(id),
    CONSTRAINT fk_pattern_check_profile FOREIGN KEY (profile_id) REFERENCES repository_pattern_profiles(id),
    CONSTRAINT ck_pr_pattern_check_status CHECK (status IN ('RUNNING','COMPLETED','FAILED'))
);
CREATE INDEX ix_pr_pattern_checks_pr ON pr_pattern_checks(pull_request_id, id);
